/**
 * Main I18n Manager Class
 */
export class I18n {
  static currentLang = (typeof localStorage !== 'undefined' && typeof localStorage.getItem === 'function')
    ? (localStorage.getItem('formulab_lang') || 'kz')
    : 'kz';

  static getLanguage() {
    return this.currentLang;
  }

  static setLanguage(lang) {
    if (lang !== 'kz' && lang !== 'ru') return;
    this.currentLang = lang;
    if (typeof localStorage !== 'undefined' && typeof localStorage.setItem === 'function') {
      localStorage.setItem('formulab_lang', lang);
    }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = lang;
    }
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('formulab_lang_change', { detail: { lang } }));
    }
  }

  static t(key) {
    const dict = UI_TRANSLATIONS[this.currentLang] || UI_TRANSLATIONS.kz;
    return dict[key] || key;
  }

  /**
   * Return a localized clone of the formula
   */
  static localizeFormula(formula, lang = null) {
    if (!formula) return null;
    const l = lang || this.currentLang;
    const trans = FORMULA_TRANSLATIONS[formula.id]?.[l];

    const localized = { ...formula };

    if (trans) {
      if (trans.title) localized.title = trans.title;
      if (trans.subtopic) localized.subtopic = trans.subtopic;
      if (trans.description) localized.description = trans.description;

      if (trans.variables && Array.isArray(formula.variables)) {
        localized.variables = formula.variables.map(v => ({
          ...v,
          name: trans.variables[v.symbol] || v.name
        }));
      }

      if (trans.targetVariable && formula.targetVariable) {
        localized.targetVariable = {
          ...formula.targetVariable,
          name: trans.targetVariable
        };
      }
    }

    return localized;
  }

  static getKazakhTaskGenerator(formulaId) {
    return KZ_TASK_GENERATORS[formulaId] || null;
  }

  /**
   * Update static DOM elements that have data-i18n attributes
   */
  static updateDOM() {
    const l = this.currentLang;
    const dict = UI_TRANSLATIONS[l];

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.placeholder = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key]) {
        el.title = dict[key];
      }
    });

    // Update active state on language switch buttons
    const btnKz = document.getElementById('lang-btn-kz');
    const btnRu = document.getElementById('lang-btn-ru');
    if (btnKz && btnRu) {
      btnKz.classList.toggle('active', l === 'kz');
      btnRu.classList.toggle('active', l === 'ru');
    }
  }
}
